"""Writes tests/samples/documents.temper.md from the files in tests/samples/docs/.

    uv run scripts/sample_docs.py          # regenerate the Temper source from docs/
    uv run scripts/sample_docs.py --fetch  # download the CommonMark spec at TAG first

The documents are real Markdown for tests and benchmarks: the CommonMark
spec's spec.txt (CC-BY-SA 4.0, so it stays in a test-only library, with
attribution in NOTICE), and READMEs of Temper libraries, kept as
snapshots so results stay comparable. Each is a plain .md file in docs/,
for tools in any language, and a Temper function giving its text, for
tests in every backend.
"""

import sys
import urllib.request
from pathlib import Path

TAG = "0.31.2"
SPEC_URL = f"https://raw.githubusercontent.com/commonmark/commonmark-spec/{TAG}/spec.txt"
ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "tests" / "samples"
DOCS = DIR / "docs"
OUT = DIR / "documents.temper.md"
CHUNK = 2000  # Code points per string literal, well under Java's limit on constants.

# File name, Temper name, and whether it's GitHub Flavored Markdown (else CommonMark).
DOCUMENTS = [
    ("commonmark-spec.md", "commonMarkSpec", False),
    ("chromarite-readme.md", "chromariteReadme", True),
    ("hrefine-readme.md", "hrefineReadme", True),
    ("kelpto-readme.md", "kelptoReadme", True),
    ("ordable-readme.md", "ordableReadme", True),
]


def literal(s: str) -> str:
    """A Temper string literal for `s`, escaping anything but plain ASCII."""
    out = []
    for ch in s:
        if " " <= ch <= "~" and ch not in '"\\$':
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):X}}}")
    return '"' + "".join(out) + '"'


def temper() -> str:
    out = [
        "# Sample documents",
        "",
        "Generated by `scripts/sample_docs.py` from the files in `docs/`. Don't",
        "edit by hand. The CommonMark spec is by John MacFarlane, under",
        "CC-BY-SA 4.0 (see NOTICE at the top of the repo).",
        "",
        "    export class SampleDocument(",
        "      public name: String,",
        "      public text: String,",
        "      public gfm: Boolean,",
        "    ) {}",
        "",
        "Each text is built from short literals, so each backend compiles it",
        "easily.",
        "",
    ]
    for file, name, _ in DOCUMENTS:
        text = (DOCS / file).read_bytes().decode("utf-8")
        out.append(f"    let {name}(): String {{")
        out.append("      let out = new StringBuilder();")
        for start in range(0, len(text), CHUNK):
            out.append(f"      out.append({literal(text[start:start + CHUNK])});")
        out.append("      out.toString()")
        out.append("    }")
        out.append("")
    out.append("Every sample, by its file name in `docs/`.")
    out.append("")
    out.append("    export let sampleDocuments(): List<SampleDocument> {")
    out.append("      [")
    for file, name, gfm in DOCUMENTS:
        out.append(f"        new SampleDocument({literal(file)}, {name}(), {'true' if gfm else 'false'}),")
    out.append("      ]")
    out.append("    }")
    return "\n".join(out) + "\n"


def main() -> None:
    if "--fetch" in sys.argv[1:]:
        with urllib.request.urlopen(SPEC_URL) as response:
            spec = response.read().decode("utf-8")
        (DOCS / "commonmark-spec.md").write_text(spec, encoding="utf-8", newline="")
    OUT.write_text(temper(), encoding="utf-8")
    sizes = ", ".join(f"{file} {len((DOCS / file).read_bytes().decode('utf-8')):,}" for file, _, _ in DOCUMENTS)
    print(f"{len(DOCUMENTS)} documents, in code points: {sizes}")


if __name__ == "__main__":
    main()

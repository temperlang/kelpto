# /// script
# requires-python = ">=3.11"
# ///
"""Extracts the CommonMark spec's examples into tests/commonmark/.

    uv run scripts/commonmark_spec.py          # regenerate the Temper source from spec.json
    uv run scripts/commonmark_spec.py --fetch  # download spec.txt at TAG first, rewriting spec.json

spec.txt is CC-BY-SA 4.0, so what comes from it (spec.json and
examples.temper.md) stays in tests/commonmark/, a test-only library
apart from the libraries' own code, with attribution in NOTICE.

Each example has its markdown input and expected HTML, with `→` standing
for a tab, as the spec's own test tools read them, and the section it's
in. Examples that need inlines beyond what kelpto-md parses so far
(emphasis, links, images, autolinks, entity references, and hard line
breaks) are marked, so the tests can hold the rest to passing. The mark
is a heuristic on the example's text, checked by hand when it changes.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

TAG = "0.31.2"
URL = f"https://raw.githubusercontent.com/commonmark/commonmark-spec/{TAG}/spec.txt"
ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "tests" / "commonmark"
JSON = DIR / "spec.json"
OUT = DIR / "examples.temper.md"
FENCE = "`" * 32
CHUNK = 100  # Examples per function, keeping each function small.

# Sections about block structure, which kelpto-md parses fully; the rest
# are about inlines.
BLOCK_SECTIONS = {
    "Tabs", "Precedence", "Thematic breaks", "ATX headings", "Setext headings",
    "Indented code blocks", "Fenced code blocks", "HTML blocks", "Link reference definitions",
    "Paragraphs", "Blank lines", "Block quotes", "List items", "Lists",
}

ENTITY = re.compile(r"&(#[0-9]{1,7}|#[xX][0-9a-fA-F]{1,6}|[A-Za-z][A-Za-z0-9]*);")
INLINE_HTML = re.compile(r"<(em|strong|a |img |br />)")
AUTOLINK = re.compile(r"<[A-Za-z][A-Za-z0-9+.-]{1,31}:[^\s<>]*>|<[^\s<>@]+@[^\s<>]+>")


def extract(spec: str) -> list[dict]:
    """The examples, as commonmark-spec's test/spec_tests.py reads them."""
    examples = []
    section = ""
    state = 0  # 0: prose, 1: markdown, 2: html
    markdown: list[str] = []
    html: list[str] = []
    for line in spec.splitlines(keepends=True):
        stripped = line.rstrip("\n")
        if state == 0:
            if stripped == FENCE + " example":
                state, markdown, html = 1, [], []
            elif re.match(r"#{1,6} ", stripped):
                section = re.sub(r"^#+ ", "", stripped).strip()
        elif state == 1:
            if stripped == ".":
                state = 2
            else:
                markdown.append(line)
        elif stripped == FENCE:
            examples.append({
                "example": len(examples) + 1,
                "section": section,
                "markdown": "".join(markdown).replace("→", "\t"),
                "html": "".join(html).replace("→", "\t"),
            })
            state = 0
        else:
            html.append(line)
    return examples


def needs_inlines(example: dict) -> bool:
    return bool(
        INLINE_HTML.search(example["html"])
        or ENTITY.search(example["markdown"])
        or AUTOLINK.search(example["markdown"])
    )


def literal(s: str) -> str:
    """A Temper string literal for `s`, escaping anything but plain ASCII."""
    out = []
    for ch in s:
        if " " <= ch <= "~" and ch not in '"\\$':
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):X}}}")
    return '"' + "".join(out) + '"'


def temper(examples: list[dict]) -> str:
    out = [
        "# CommonMark spec examples",
        "",
        f"Generated by `scripts/commonmark_spec.py` from CommonMark's spec.txt,",
        f"tag {TAG}, by John MacFarlane, under CC-BY-SA 4.0 (see NOTICE at the",
        "top of the repo). Don't edit by hand.",
        "",
        "Each example: its number, its section, the Markdown, the expected",
        "HTML, whether it's about block structure, and whether it needs",
        "inlines kelpto-md doesn't parse yet.",
        "",
        "    export class SpecExample(",
        "      public number: Int,",
        "      public section: String,",
        "      public markdown: String,",
        "      public html: String,",
        "      public isBlock: Boolean,",
        "      public needsInlines: Boolean,",
        "    ) {}",
        "",
        "In functions rather than a module-level list, and in chunks, so each",
        "backend compiles them easily.",
        "",
    ]
    names = []
    for start in range(0, len(examples), CHUNK):
        name = f"examples{start // CHUNK}"
        names.append(name)
        out.append(f"    let {name}(): List<SpecExample> {{")
        out.append("      [")
        for ex in examples[start:start + CHUNK]:
            args = ", ".join([
                str(ex["example"]), literal(ex["section"]), literal(ex["markdown"]),
                literal(ex["html"]), "true" if ex["section"] in BLOCK_SECTIONS else "false",
                "true" if needs_inlines(ex) else "false",
            ])
            out.append(f"        new SpecExample({args}),")
        out.append("      ]")
        out.append("    }")
        out.append("")
    out.append("All the examples, in order.")
    out.append("")
    out.append("    export let specExamples(): List<SpecExample> {")
    out.append("      let all = new ListBuilder<SpecExample>();")
    for name in names:
        out.append(f"      all.addAll({name}());")
    out.append("      all.toList()")
    out.append("    }")
    return "\n".join(out) + "\n"


def main() -> None:
    if "--fetch" in sys.argv[1:] or not JSON.exists():
        with urllib.request.urlopen(URL) as response:
            spec = response.read().decode("utf-8")
        examples = extract(spec)
        DIR.mkdir(parents=True, exist_ok=True)
        JSON.write_text(json.dumps(examples, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    examples = json.loads(JSON.read_text(encoding="utf-8"))
    OUT.write_text(temper(examples), encoding="utf-8")
    blocks = [ex for ex in examples if ex["section"] in BLOCK_SECTIONS]
    print(f"{len(examples)} examples, {len(blocks)} in block sections, "
          f"{sum(needs_inlines(ex) for ex in blocks)} of those needing inlines")


if __name__ == "__main__":
    main()

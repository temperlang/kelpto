"""Extracts GitHub Flavored Markdown's examples into tests/gfm/.

    uv run scripts/gfm_spec.py          # regenerate the Temper source from spec.json
    uv run scripts/gfm_spec.py --fetch  # download the files at TAG first, rewriting spec.json

Two files from cmark-gfm, GitHub's reference implementation, at a pinned
tag, each checked against its SHA-256:

- test/spec.txt, the GFM spec, whose examples are tagged with the
  extension they need (`example table`, say), or `disabled`;
- test/extensions.txt, cmark-gfm's own tests of the extensions, run with
  all of them on. Its footnote examples are left out, since kelpto-md
  doesn't do footnotes.

Both are CC-BY-SA 4.0, so what comes from them (spec.json and
examples.temper.md) stays in tests/gfm/, a test-only library apart from
the libraries' own code, with attribution in NOTICE.
"""

import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

from commonmark_spec import FENCE, literal

TAG = "0.29.0.gfm.13"
COMMIT = "587a12bb54d95ac37241377e6ddc93ea0e45439b"
BASE = f"https://raw.githubusercontent.com/github/cmark-gfm/{COMMIT}/test"
FILES = {
    "spec.txt": "7d8e5814befec287ac116786d81ff14e0adc9b13295b4494649e995408fd871c",
    "extensions.txt": "a2a45e98be9fca95f564f927265a0f63beea6cae5369d1cf4bde44caa51b2a3a",
}
ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "tests" / "gfm"
JSON = DIR / "spec.json"
OUT = DIR / "examples.temper.md"
CHUNK = 100  # Examples per function, keeping each function small.


def extract(text: str, source: str) -> list[dict]:
    """The examples, as cmark-gfm's test/spec_tests.py reads them, with
    the words after `example` as the extensions each needs."""
    examples = []
    section = ""
    state = 0  # 0: prose, 1: markdown, 2: html
    markdown: list[str] = []
    html: list[str] = []
    tags: list[str] = []
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        if state == 0:
            if stripped.startswith(FENCE + " example"):
                state, markdown, html = 1, [], []
                tags = stripped[len(FENCE) + len(" example"):].split()
            elif re.match(r"#+ ", line):
                section = re.sub(r"^#+ ", "", line).strip()
        elif state == 1:
            if stripped == ".":
                state = 2
            else:
                markdown.append(line)
        elif stripped == FENCE:
            examples.append({
                "source": source,
                "example": len(examples) + 1,
                "section": section,
                "extension": " ".join(tags),
                "markdown": "".join(markdown).replace("→", "\t"),
                "html": "".join(html).replace("→", "\t"),
            })
            state = 0
        else:
            html.append(line)
    return examples


def fetch(name: str) -> str:
    with urllib.request.urlopen(f"{BASE}/{name}") as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != FILES[name]:
        sys.exit(f"{name}: SHA-256 {digest}, expected {FILES[name]}")
    return data.decode("utf-8")


def temper(examples: list[dict]) -> str:
    out = [
        "# GFM examples",
        "",
        "Generated by `scripts/gfm_spec.py` from cmark-gfm's test/spec.txt (the",
        f"GFM spec) and test/extensions.txt, tag {TAG}, under CC-BY-SA 4.0 (see",
        "NOTICE at the top of the repo). Don't edit by hand.",
        "",
        "Each example: where it's from (`spec` or `extensions`), its number",
        "there, its section, the extension it needs (`table`,",
        "`strikethrough`, `autolink`, `tagfilter`, or `disabled`; empty for",
        "plain CommonMark, and for every one from extensions.txt, which runs",
        "with all of them), the Markdown, and the expected HTML.",
        "",
        "    export class GfmExample(",
        "      public source: String,",
        "      public number: Int,",
        "      public section: String,",
        "      public extension: String,",
        "      public markdown: String,",
        "      public html: String,",
        "    ) {}",
        "",
        "In functions rather than a module-level list, and in chunks, so each",
        "backend compiles them easily.",
        "",
    ]
    names = []
    for start in range(0, len(examples), CHUNK):
        name = f"examples{start // CHUNK}"
        names.append(name)
        out.append(f"    let {name}(): List<GfmExample> {{")
        out.append("      [")
        for ex in examples[start:start + CHUNK]:
            args = ", ".join([
                literal(ex["source"]), str(ex["example"]), literal(ex["section"]),
                literal(ex["extension"]), literal(ex["markdown"]), literal(ex["html"]),
            ])
            out.append(f"        new GfmExample({args}),")
        out.append("      ]")
        out.append("    }")
        out.append("")
    out.append("All the examples, the spec's first.")
    out.append("")
    out.append("    export let gfmExamples(): List<GfmExample> {")
    out.append("      let all = new ListBuilder<GfmExample>();")
    for name in names:
        out.append(f"      all.addAll({name}());")
    out.append("      all.toList()")
    out.append("    }")
    return "\n".join(out) + "\n"


def main() -> None:
    if "--fetch" in sys.argv[1:] or not JSON.exists():
        spec = extract(fetch("spec.txt"), "spec")
        extensions = [
            ex for ex in extract(fetch("extensions.txt"), "extensions")
            if not ex["section"].lower().startswith("footnote")
            and "footnote" not in ex["section"].lower()
        ]
        DIR.mkdir(parents=True, exist_ok=True)
        JSON.write_text(
            json.dumps(spec + extensions, ensure_ascii=False, indent=1) + "\n", encoding="utf-8",
        )
    examples = json.loads(JSON.read_text(encoding="utf-8"))
    OUT.write_text(temper(examples), encoding="utf-8")
    counts: dict[str, int] = {}
    for ex in examples:
        key = f"{ex['source']}:{ex['extension'] or '-'}"
        counts[key] = counts.get(key, 0) + 1
    print(", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
